def t(lang: str, key: str) -> str:
    table = STRINGS.get(lang) or _EN
    return table.get(key) or _EN.get(key) or key


def flash_key(label: str) -> str:
    mapping = {
        "Copied": "flash_copied",
        "Saved": "flash_saved",
        "Correcting": "flash_correcting",
        "Empty": "flash_empty",
        "Loading": "flash_loading",
        "Error": "flash_error",
    }
    return mapping.get(label, "")
